export type CaseStudyId = (typeof caseStudyIds)[number];
export type SectionId = CaseStudyId | "general";
export type Difficulty = "Intermediate" | "Advanced";

type Option = { id: string; text: string };
type Source = { label: string; url: string };

type QuestionBase = {
  id: number;
  section: SectionId;
  domain: Domain;
  objective: string;
  difficulty: Difficulty;
  stem: string;
  context?: string;
  explanation: string;
  source: Source;
};

export type SingleQuestion = QuestionBase & {
  type: "single";
  options: Option[];
  correct: string;
};

export type MultiQuestion = QuestionBase & {
  type: "multi";
  options: Option[];
  correct: string[];
  selectCount: number;
};

export type OrderQuestion = QuestionBase & {
  type: "order";
  options: Option[];
  correct: string[];
};

export type MatchQuestion = QuestionBase & {
  type: "match";
  prompts: Option[];
  choices: Option[];
  correct: Record<string, string>;
};

export type MatrixQuestion = QuestionBase & {
  type: "matrix";
  rows: Option[];
  columns: Option[];
  correct: Record<string, string>;
};

export type Question =
  | SingleQuestion
  | MultiQuestion
  | OrderQuestion
  | MatchQuestion
  | MatrixQuestion;

export type CaseStudy = {
  id: CaseStudyId;
  title: string;
  subtitle: string;
  tabs: { label: string; content: string[] }[];
};

